def normalize_country(value):
    if pd.isna(value):
        return "UNKNOWN"
    text = str(value).strip()
    if not text:
        return "UNKNOWN"
    text = re.sub(r"\([^)]*\)", " ", text)
    text = unicodedata.normalize("NFKD", text)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    text = text.casefold().replace("&", " and ")
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()

alias_lookup = {}
ambiguous_aliases = set()

for code, aliases in country_aliases.items():
    for alias in aliases + [code]:
        normalized = normalize_country(alias)
        if normalized in alias_lookup and alias_lookup[normalized] != code:
            ambiguous_aliases.add(normalized)
        else:
            alias_lookup[normalized] = code

for alias in ambiguous_aliases:
    alias_lookup.pop(alias, None)

def to_iso2(value):
    normalized = normalize_country(value)
    if normalized in {"", "unknown", "na", "n a", "none", "null", "nan", "not specified", "notspecified", "other"}:
        return "UNKNOWN"
    return alias_lookup.get(normalized, "UNKNOWN")

