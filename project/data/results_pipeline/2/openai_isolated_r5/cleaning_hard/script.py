alias_to_code = {}
for code, aliases in country_aliases.items():
    alias_to_code[normalize_value(code)] = code
    for alias in aliases:
        normalized_alias = normalize_value(alias)
        if normalized_alias:
            alias_to_code[normalized_alias] = code

ambiguous_values = {
    "congo", "korea", "korean", "guinea",
    "virgin islands", "amerikanische jungferninseln", "britische jungferninseln",
}

def map_country(value):
    normalized = normalize_value(value)
    if not normalized or normalized in ambiguous_values:
        return "UNKNOWN"
    return alias_to_code.get(normalized, "UNKNOWN")

df["country"] = df["country"].map(map_country).astype("string")

