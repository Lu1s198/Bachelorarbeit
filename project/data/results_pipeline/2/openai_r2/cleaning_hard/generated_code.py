def normalize(value):
    if pd.isna(value):
        return ""
    text = str(value).strip().replace("ß", "ss").replace("ẞ", "SS")
    text = unicodedata.normalize("NFKD", text)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    return re.sub(r"[^A-Z0-9]+", "", text.upper())

lookup = {}
for code, names in aliases.items():
    lookup[normalize(code)] = code
    for name in names.split(","):
        lookup[normalize(name)] = code

def standardize_country(value):
    key = normalize(value)
    if not key:
        return "UNKNOWN"
    if key in lookup:
        return lookup[key]
    raw = str(value)
    candidates = re.findall(r"[A-Za-zÀ-ÿ0-9.'-]+(?:\s+[A-Za-zÀ-ÿ0-9.'-]+){0,6}", raw)
    found = {lookup[normalize(candidate)] for candidate in candidates if normalize(candidate) in lookup}
    return found.pop() if len(found) == 1 else "UNKNOWN"

df = pd.read_parquet(input_path)
df["country"] = df["country"].map(standardize_country).astype("string")

