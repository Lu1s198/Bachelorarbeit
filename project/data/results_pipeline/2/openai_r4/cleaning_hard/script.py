def normalize_country(value):
    if pd.isna(value):
        return ""
    text = str(value).strip().lower()
    text = unicodedata.normalize("NFKD", text)
    text = "".join(char for char in text if not unicodedata.combining(char))
    text = text.replace("&", " and ")
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()

lookup = {}
for iso_code, aliases in country_aliases.items():
    lookup[normalize_country(iso_code)] = iso_code
    for alias in aliases:
        normalized_alias = normalize_country(alias)
        if normalized_alias:
            lookup[normalized_alias] = iso_code

normalized_country = data["country"].map(normalize_country)
data["country"] = normalized_country.map(lookup).fillna("UNKNOWN").astype("string")

